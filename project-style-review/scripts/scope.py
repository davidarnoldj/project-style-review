MAX_BYTES = 192 * 1024
INSTRUCTIONS = {"agents.md", "agents.override.md", "claude.md"}
SKIP_DIRS = {
    ".git", ".hg", ".svn", ".aws", ".gnupg", ".kube", ".ssh",
    ".build", ".cache", ".gradle", ".idea", ".mypy_cache",
    ".next", ".pytest_cache", ".ruff_cache", ".swiftpm", ".tox", ".venv", ".env",
    "__pycache__", "build", "coverage", "deriveddata", "dist", "generated",
    "node_modules", "pods", "target", "vendor", "vendored", "venv", "third_party",
    "_vendor", "carthage", "secrets", "credentials",
}
SUFFIXES = {
    ".py", ".pyi", ".sql", ".swift", ".md", ".markdown", ".mdx", ".rst", ".adoc",
    ".txt", ".toml", ".yaml", ".yml", ".json", ".jsonc", ".ini", ".cfg", ".conf",
    ".xml", ".plist", ".strings", ".stringsdict", ".xcstrings", ".arb", ".po",
    ".pot", ".properties", ".xcconfig", ".sh", ".bash", ".zsh", ".js", ".jsx",
    ".ts", ".tsx", ".css", ".html", ".qml",
}
TEXT_NAMES = {
    "readme", "changelog", "contributing", "glossary", "license", "licence",
    "notice", "copying", "makefile", "dockerfile", ".gitignore", ".ignore",
    ".editorconfig", ".gitattributes",
}
SECRET_NAME = re.compile(
    r"^(?:\.env(?:rc|[.-].*)?|\.netrc|\.npmrc|\.pypirc|\.git-credentials|"
    r"id_(?:rsa|dsa|ecdsa|ed25519)(?:[.-].*)?|"
    r"(?:.*[-_.])?(?:secrets?|credentials?|service[-_]account|"
    r"client[-_]secret|private[-_]key|access[-_]token)(?:[._-].*)?)$"
)
SECRET_SUFFIXES = {".pem", ".key", ".p8", ".p12", ".pfx", ".keystore", ".jks"}
SECRET_TEXT = re.compile(
    r"-----BEGIN [A-Z ]*PRIVATE KEY-----|\b(?:gh[pousr]_|github_pat_|"
    r"xox[baprs]-|sk-(?:proj-|live_)?)[A-Za-z0-9_-]{20,}|\bAKIA[A-Z0-9]{16}\b|"
    r"""(?im:^\s*["']?(?:password|passwd|api[_-]?key|client[_-]?secret|"""
    r"""access[_-]?token)["']?\s*[:=]\s*["']?[A-Za-z0-9_+./=-]{8,})"""
)
GENERATED = re.compile(
    r"^\s*(?://+|#+|/\*+|\*|--|<!--)\s*(?:@generated\b|"
    r"do not edit\b|(?:code |file )?(?:auto[- ]?)?generated by\b|"
    r"this file (?:is|was) (?:auto[- ]?)?generated\b)",
    re.IGNORECASE,
)
GENERATED_NAME = re.compile(r"(?:[._-](?:generated|min|bundle)\.|_pb2\.py$|\.pb\.swift$)")
LOCK_NAMES = {"package.resolved", "package-lock.json", "npm-shrinkwrap.json", "bun.lock"}
# Keep inherited Git settings from redirecting discovery to another checkout or index.
GIT_ENV = {key: value for key, value in os.environ.items() if not key.startswith("GIT_")}
GIT_ENV.update(GIT_OPTIONAL_LOCKS="0", GIT_NO_LAZY_FETCH="1", GIT_TERMINAL_PROMPT="0",
               GIT_LITERAL_PATHSPECS="1", LC_ALL="C")


class ScopeError(Exception):
    pass


class Excluded(Exception):
    pass


def safe_read(root, relative):
    """Read bounded regular files without opening symlink components."""
    with ExitStack() as stack:
        directory_flags = os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW
        fd = os.open(root, directory_flags)
        stack.callback(os.close, fd)
        for parent in relative.parts[:-1]:
            try:
                fd = os.open(parent, directory_flags, dir_fd=fd)
            except NotADirectoryError as error:
                raise Excluded("symlink or non-directory parent") from error
            stack.callback(os.close, fd)
        try:
            file_fd = os.open(relative.name, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK,
                              dir_fd=fd)
        except OSError as error:
            if error.errno == errno.ELOOP:
                raise Excluded("symlink") from error
            raise
        with os.fdopen(file_fd, "rb") as stream:
            info = os.fstat(stream.fileno())
            if not stat.S_ISREG(info.st_mode):
                raise Excluded("non-regular")
            if info.st_size > MAX_BYTES:
                raise Excluded("size limit")
            data = stream.read(MAX_BYTES + 1)
            if len(data) > MAX_BYTES:
                raise Excluded("size limit")
            return data


def inspect_text(data, delivery=False):
    try:
        encoding = "utf-16" if data.startswith((b"\xff\xfe", b"\xfe\xff")) else "utf-8-sig"
        text = data.decode(encoding)
    except UnicodeError as error:
        raise Excluded("binary or unsupported encoding") from error
    if any(ord(c) < 32 and c not in "\t\r\n\f" for c in text):
        raise Excluded("binary or unsupported encoding")
    if SECRET_TEXT.search(text):
        raise Excluded("possible secret")
    if not delivery and any(GENERATED.match(line) for line in text.splitlines()[:12]):
        raise Excluded("generated header")
    return text


def path_exclusion(path, delivery):
    name = path.name.lower()
    if any(part.lower() in SKIP_DIRS for part in path.parts[:-1]):
        return "excluded directory"
    if SECRET_NAME.match(name) or path.suffix.lower() in SECRET_SUFFIXES:
        return "possible secret path"
    if name in LOCK_NAMES or name.endswith(".lock"):
        return "lockfile"
    if GENERATED_NAME.search(name) and not delivery:
        return "generated filename"
    if (name not in TEXT_NAMES and path.suffix.lower() not in SUFFIXES
            and not re.fullmatch(r"(?:license|licence|copying|notice)\.[\w.-]+", name)):
        return "unsupported file type"
    return None


def wildcard(pattern):
    """Translate Git-style wildcards, with * confined to one component."""
    result = []
    i = 0
    while i < len(pattern):
        char = pattern[i]
        if char == "\\" and i + 1 < len(pattern):
            i += 1
            result.append(re.escape(pattern[i]))
        elif char == "*":
            start = i
            while i + 1 < len(pattern) and pattern[i + 1] == "*":
                i += 1
            whole_component = (start == 0 or pattern[start - 1] == "/")
            if i > start and whole_component and pattern[i + 1:i + 2] == "/":
                result.append("(?:[^/]+/)*")
                i += 1
            elif i > start and start > 0 and whole_component and i + 1 == len(pattern):
                result.append(".*")
            else:
                result.append("[^/]*")
        elif char == "?":
            result.append("[^/]")
        elif char == "[":
            start = i + 1
            if pattern[start:start + 1] in ("!", "^"):
                start += 1
            if pattern[start:start + 1] == "]":
                start += 1
            end = pattern.find("]", start)
            if end == -1:
                return None
            members = pattern[i + 1:end]
            if "[:" in members:
                return None
            if members[0] == "!":
                members = "^" + members[1:]
            result.append("(?!/)[" + members + "]")
            i = end
        else:
            result.append(re.escape(char))
        i += 1
    try:
        return re.compile("".join(result), re.DOTALL)
    except re.error:
        return None


@dataclass
class Rule:
    base: Path
    pattern: re.Pattern
    basename_only: bool
    directory_only: bool
    include: bool

    def matches(self, path, directory):
        if self.directory_only and not directory:
            return False
        local = path.relative_to(self.base)
        return self.pattern.fullmatch(local.name if self.basename_only else local.as_posix())


def ignore_rules(root, directory):
    for name in (".gitignore", ".ignore"):
        try:
            text = safe_read(root, directory / name).decode("utf-8-sig")
        except (FileNotFoundError, Excluded) as error:
            if isinstance(error, Excluded) and str(error) != "symlink":
                raise
            continue
        for line in text.splitlines():
            while line.endswith(" "):
                if (len(line) - 1 - len(line[:-1].rstrip("\\"))) % 2:
                    break
                line = line[:-1]
            if not line or line.startswith("#"):
                continue
            include = line.startswith("!")
            pattern = line[1:] if include else line
            directory_only = pattern.endswith("/")
            if directory_only:
                pattern = pattern[:-1]
            basename_only = "/" not in pattern
            expression = wildcard(pattern.removeprefix("/"))
            if expression is None:
                raise Excluded("unsupported ignore pattern")
            yield Rule(directory, expression, basename_only, directory_only, include)


def ordinary_paths(root, selectors, skipped):
    rules_by_dir = {}

    def error_handler(_):
        skipped["unreadable directory"] += 1

    for directory, dirs, files in os.walk(root, onerror=error_handler):
        relative = Path(directory).relative_to(root)
        inherited = rules_by_dir.pop(relative, ())
        try:
            rules = (*inherited, *ignore_rules(root, relative))
        except (OSError, UnicodeError, Excluded):
            skipped["unusable ignore rules (directory pruned)"] += 1
            dirs[:] = []
            continue
        chosen_dirs = []
        for name, is_dir in chain(((name, True) for name in dirs),
                                  ((name, False) for name in files)):
            path = relative / name
            if selectors and not any(
                selector == path or selector in path.parents or (is_dir and path in selector.parents)
                for selector in selectors
            ):
                continue
            if (root / path).is_symlink():
                skipped["symlink"] += 1
                continue
            if is_dir and name.lower() in SKIP_DIRS:
                skipped["excluded directory"] += 1
                continue
            matching = next((rule for rule in reversed(rules) if rule.matches(path, is_dir)), None)
            if matching and not matching.include:
                skipped["ignored entry"] += 1
                continue
            if is_dir:
                chosen_dirs.append(name)
                rules_by_dir[path] = rules
            else:
                yield path, []
        dirs[:] = sorted(chosen_dirs)


class GitScope:
    def __init__(self, root, top):
        self.root = root
        self.top = top
        self.prefix = root.relative_to(top)
        self.safety_config = []
        keys = self.run("config", "--null", "--name-only", "--get-regexp",
                        r"^filter\..*\.(clean|process|required)$", allow_missing=True)
        for driver in sorted({key.rsplit(".", 1)[0] for key in split_z(keys)}):
            self.safety_config.extend(("-c", f"{driver}.clean=", "-c", f"{driver}.process=",
                                       "-c", f"{driver}.required=false"))

    def run(self, *args, directory=None, allow_missing=False):
        output = git(directory or self.top, *self.safety_config, *args)
        if output.returncode == 1 and allow_missing:
            return b""
        if output.returncode:
            raise ScopeError(f"Git {args[0]} failed (exit {output.returncode})")
        return output.stdout

    def paths(self, changes, base, selectors, skipped):
        pathspec = [str(self.prefix / path) for path in selectors] or [str(self.prefix)]
        common = ("--", *pathspec)
        ignored = self.run("ls-files", "-z", "--others", "--ignored", "--exclude-standard",
                           "--directory", "--no-empty-directory", *common)
        skipped["Git-ignored entries"] += len(split_z(ignored))
        untracked = split_z(self.run("ls-files", "-z", "--others", "--exclude-standard", *common))
        groups = defaultdict(list)
        if not changes:
            tracked = split_z(self.run("ls-files", "-z", "--cached", *common))
            groups.update((name, []) for name in set(tracked) | set(untracked))
        else:
            diff = ("diff", "--name-only", "-z", "--no-ext-diff", "--no-textconv",
                    "--no-renames", "--ignore-submodules=all")
            comparisons = []
            if base:
                comparisons.append(("committed", self.run(*diff, base, "HEAD", *common)))
            comparisons.extend((("staged", self.run(*diff, "--cached", *common)),
                                ("unstaged", self.run(*diff, *common))))
            for layer, paths in comparisons:
                for name in set(split_z(paths)):
                    groups[name].append(layer)
            for name in untracked:
                groups[name].append("untracked")
        for name, layers in groups.items():
            full_path = Path(name)
            if full_path.is_absolute() or ".." in full_path.parts:
                raise ScopeError("Git returned an unsafe path")
            try:
                yield full_path.relative_to(self.prefix), layers
            except ValueError:
                continue

    def snapshot(self, path, revision, delivery):
        full = str(self.prefix / path)
        if revision is None:
            entries = split_z(self.run("ls-files", "--stage", "-z", "--", full))
            if not entries:
                return ""
            if len(entries) != 1:
                raise Excluded("unmerged index")
            mode, oid, stage = entries[0].split("\t", 1)[0].split()
            if stage != "0":
                raise Excluded("unmerged index")
        else:
            if revision == "HEAD" and not self.run("rev-parse", "--verify", "--quiet", "HEAD", allow_missing=True):
                return ""
            entries = split_z(self.run("ls-tree", "-z", revision, "--", full))
            if not entries:
                return ""
            mode, _, oid = entries[0].split("\t", 1)[0].split()
        if mode not in ("100644", "100755"):
            raise Excluded("non-regular Git snapshot")
        if int(self.run("cat-file", "-s", oid)) > MAX_BYTES:
            raise Excluded("size limit")
        return inspect_text(self.run("cat-file", "blob", oid), delivery)


def git(root, *args):
    return subprocess.run(
        ["git", "--no-pager", "--no-optional-locks", "-c", "core.fsmonitor=false",
         "-C", os.fspath(root), *args],
        capture_output=True, env=GIT_ENV, check=False, timeout=30,
    )


def split_z(data):
    return [os.fsdecode(item) for item in data.split(b"\0") if item]


def get_git(root):
    has_marker = any(os.path.lexists(parent / ".git") for parent in (root, *root.parents))
    try:
        result = git(root, "rev-parse", "--show-toplevel")
    except FileNotFoundError:
        if has_marker:
            raise ScopeError("Git executable unavailable for this working tree")
        return None
    if result.returncode:
        if has_marker:
            raise ScopeError("Git could not resolve this working tree")
        return None
    top = Path(os.fsdecode(result.stdout.removesuffix(b"\n"))).resolve()
    return GitScope(root, top)


def resolve_root(requested):
    absolute = Path(os.path.abspath(requested))
    physical = absolute
    if sys.platform == "darwin":
        for alias in (Path("/var"), Path("/tmp"), Path("/etc")):
            if absolute == alias or alias in absolute.parents:
                standard_target = Path("/private") / alias.name
                if alias.is_symlink() and os.readlink(alias) in {
                    str(standard_target), str(standard_target).lstrip("/")
                }:
                    physical = standard_target / absolute.relative_to(alias)
                break
    if any(part.is_symlink() for part in (*reversed(physical.parents), physical)):
        raise ScopeError("the requested review root passes through a symlink")
    return absolute, physical.resolve(strict=True)


def relative_arg(root, requested_root, value):
    path = Path(value)
    if ".." in path.parts:
        raise ScopeError(f"parent traversal is outside this interface: {value}")
    if path.is_absolute():
        try:
            path = path.relative_to(requested_root if path.is_relative_to(requested_root) else root)
        except ValueError as error:
            raise ScopeError(f"path is outside the review scope: {value}") from error
    return path


def source_lines(text):
    return text.replace("\r\n", "\n").replace("\r", "\n").removesuffix("\n").split("\n") if text else []


def patch(git_scope, path, worktree, layers, base, delivery):
    snapshots = {}
    comparisons = {
        "committed": (base, "HEAD"), "staged": ("HEAD", None),
        "unstaged": (None, "working tree"), "untracked": ("empty", "working tree"),
    }
    result = {}
    for layer in layers:
        before, after = comparisons[layer]
        for revision in (before, after):
            if revision not in snapshots:
                if revision == "working tree":
                    snapshots[revision] = worktree
                elif revision == "empty":
                    snapshots[revision] = ""
                else:
                    snapshots[revision] = git_scope.snapshot(path, revision, delivery)
        diff = unified_diff(source_lines(snapshots[before]), source_lines(snapshots[after]),
                            fromfile=str(path), tofile=str(path), lineterm="")
        result[layer] = "\n".join(diff)
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("root", type=Path)
    parser.add_argument("paths", nargs="*", help="literal files or subdirectories inside root")
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--changes", action="store_true", help="working-tree Git changes")
    mode.add_argument("--base", metavar="REV", help="add REV-to-HEAD changes to working-tree changes")
    output = parser.add_mutually_exclusive_group()
    output.add_argument("--read", action="store_true", help="return text for explicit file paths")
    output.add_argument("--patch", action="store_true", help="return separate Git patches for explicit files")
    parser.add_argument("--delivery", action="store_true", help="allow generated headers in explicit files")
    parser.add_argument("--limit", type=int, default=200, help="maximum paths emitted in a listing")
    args = parser.parse_intermixed_args()
    changes = args.changes or args.base is not None
    if (args.read or args.patch or args.delivery) and not args.paths:
        parser.error("--read, --patch and --delivery require explicit file paths")
    if args.patch and not changes:
        parser.error("--patch requires --changes or --base")
    if args.limit < 1:
        parser.error("--limit must be positive")
    requested_root, root = resolve_root(args.root)
    if not root.is_dir():
        raise ScopeError("root must be a directory")
    selectors = {relative_arg(root, requested_root, name) for name in args.paths}

    repo = get_git(root)
    if changes and repo is None:
        raise ScopeError("change review requires a Git working tree")
    base = None
    if args.base is not None:
        base = repo.run("rev-parse", "--verify", "--end-of-options", f"{args.base}^{{commit}}").decode().strip()
    skipped = Counter()
    records = []
    rejected = {}
    paths = (repo.paths(changes, base, selectors, skipped) if repo
             else ordinary_paths(root, selectors, skipped))
    for path, layers in paths:
        if (args.read or args.patch or args.delivery) and path not in selectors:
            continue
        if path == Path("."):
            skipped["non-regular"] += 1
            continue
        reason = path_exclusion(path, args.delivery)
        if reason:
            skipped[reason] += 1
            rejected[path] = reason
            continue
        try:
            present = True
            try:
                content = inspect_text(safe_read(root, path), args.delivery)
            except FileNotFoundError:
                if not changes:
                    raise
                present, content = False, ""
            record = {"path": str(path), "layers": layers, "present": present}
            if args.patch:
                record["patches"] = patch(repo, path, content, layers, base, args.delivery)
            elif args.read:
                record["numbered_text"] = "\n".join(
                    f"{number}\t{line}" for number, line in enumerate(source_lines(content), 1)
                )
            records.append(record)
        except (Excluded, OSError) as error:
            reason = str(error) if isinstance(error, Excluded) else "missing or unreadable file"
            skipped[reason] += 1
            rejected[path] = reason

    records.sort(key=lambda record: (len(Path(record["path"]).parts), record["path"]))
    found = {Path(record["path"]) for record in records}
    unresolved = {str(path): rejected.get(path, "no eligible match")
                  for path in sorted(selectors) if path not in found and
                  not any(path in matched.parents for matched in found)}
    cap = len(records) if args.read or args.patch else args.limit
    instructions = [record["path"] for record in records
                    if Path(record["path"]).name.lower() in INSTRUCTIONS]
    print(json.dumps({
        "root": str(root), "mode": "git-changes" if changes else "git-tree" if repo else "folder",
        "eligible": len(records), "omitted_by_limit": max(0, len(records) - cap),
        "instructions": instructions[:args.limit],
        "files": records[:cap], "skipped_entries": dict(sorted(skipped.items())),
        "unresolved_selections": unresolved,
    }, ensure_ascii=True, indent=2))


if __name__ == "__main__":
    try:
        main()
    except (ScopeError, OSError, subprocess.TimeoutExpired) as error:
        print(f"scope: {error}", file=sys.stderr)
        sys.exit(2)
